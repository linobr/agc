// Full no-code production path: UI + real keyboard only; synthetic scan remains local.
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { roomFile } from '../tests/fixture.js';
const url=process.argv[2] || 'http://127.0.0.1:4189/agc/';
const browser=await chromium.launch({args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist']});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(/\.(js|css)(\?|$)/.test(r.url()) && r.status()>=400) errors.push(`${r.status()} ${r.url()}`);});
  page.on('requestfailed',r=>{if(/\.(js|css)(\?|$)/.test(r.url())) errors.push(r.url());});
  const response=await page.goto(url);assert.equal(response.status(),200);
  await page.locator('#addTrigger').waitFor();assert.equal(await page.evaluate(()=>typeof window.agcDebug),'undefined');
  await page.locator('#fileInput').setInputFiles(roomFile());await page.getByText(/2 walkable candidates/).waitFor();
  const fill=async(id,value)=>{await page.locator(`#${id}`).fill(String(value));await page.locator(`#${id}`).press('Tab');};
  await fill('spawnX',-3);await fill('spawnY',.04);await fill('spawnZ',0);
  await page.locator('#addTrigger').click();await page.locator('#gameAddRule').click();
  await page.getByLabel('Rule 1 text',{exact:true}).fill('You found the exit');await page.getByLabel('Rule 1 text',{exact:true}).press('Tab');
  await page.locator('#addGoal').click();await page.locator('#gameRequireAll').check();
  await page.locator('#addCollectible').click();await fill('game-position-z',-2);
  await page.locator('#gameAddRule').click();await page.getByLabel('Rule 1 action',{exact:true}).selectOption('completeObjective');
  await page.getByLabel('Rule 1 objective',{exact:true}).fill('Token found');await page.getByLabel('Rule 1 objective',{exact:true}).press('Tab');
  await page.locator('#gameBtn').click();
  await page.waitForFunction(()=>document.querySelector('#gameMessage').textContent.includes('Collect all items'));
  assert.equal(await page.locator('#gameWin').isVisible(),false);
  await page.keyboard.down('w');
  await page.waitForFunction(()=>document.querySelector('#gameHudCount').textContent==='Collectibles: 1 / 1');await page.keyboard.up('w');
  assert.match(await page.locator('#gameHudObjectives').textContent(),/Token found/);
  await page.keyboard.down('s');await page.locator('#gameWin').waitFor();await page.keyboard.up('s');
  assert.equal(await page.locator('#gameMessage').textContent(),'You found the exit');
  assert.match(await page.locator('#gameWinStats').textContent(),/Collectibles: 1 \/ 1/);
  await mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/production-game-win.png'});
  await page.locator('#gameWinRestart').click();
  await page.waitForFunction(()=>document.querySelector('#gameHudCount').textContent==='Collectibles: 0 / 1');
  await page.locator('#gameExit').click();assert.equal(await page.locator('#sceneStatus').textContent(),'EDITOR MODE');
  const download=page.waitForEvent('download');await page.locator('#exportBtn').click();await (await download).saveAs('test-results/production-game.agc');
  const saved=JSON.parse(await readFile('test-results/production-game.agc','utf8'));
  assert.equal(saved.version,3);assert.equal(saved.gameplay.length,3);assert.equal(saved.gameplay[1].requireAll,true);
  assert.equal(saved.gameplay.some(o=>'collected' in o),false);
  await page.reload();await page.locator('#projectInput').setInputFiles({name:'production-game.agc',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
  await page.locator('#projectScanInput').setInputFiles(roomFile());
  await page.waitForFunction(()=>document.querySelector('#projectStatus').textContent.includes('Project opened'));
  assert.equal(await page.locator('#gameCount').textContent(),'3/100');
  await page.locator('#gameBtn').click();await page.waitForFunction(()=>document.querySelector('#gameHudCount').textContent==='Collectibles: 0 / 1');
  await page.locator('#gameExit').click();
  await page.locator('#gameObjectSelect').selectOption(saved.gameplay[2].id);await fill('game-size-x',.8);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({url,http:response.status(),errors,game:'UI rules, blocked goal, keyboard pickup/win, objective, restart, v3 save/open and editor verified'}));
} finally { await browser.close(); }
